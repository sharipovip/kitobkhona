function translateTextNode(node, lang) {
  const original = kkhOriginalText.has(node) ? kkhOriginalText.get(node) : node.nodeValue;
  if (!kkhOriginalText.has(node)) kkhOriginalText.set(node, original);
  const trimmed = original.trim();
  if (!trimmed) return;
  const translated = lookupKkhTranslation(trimmed, lang);
  const next = translated !== null ? original.replace(trimmed, translated) : original;
  if (node.nodeValue !== next) node.nodeValue = next;
}
const KKH_TRANSLATION_SKIP_SELECTOR = '[data-no-translate],[alt^="Обложка:"],.page-slot,.page-container,.book-content,.book-text,.book-name,.book-info-v3 b,.book-author-v3,.continue-book-title,.marquee-text,.cover,.art-title,.art-text,.news-title,.news-sub,.news-desc-media,.bubble-text,.slide-text-overlay,.slide-hashtag,.comment-text';
function translatePage(lang) {
  const root = document.body;
  if (!root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    const parent = node.parentElement;
    if (parent && !['SCRIPT','STYLE','TEXTAREA'].includes(parent.tagName) && !parent.closest(KKH_TRANSLATION_SKIP_SELECTOR)) translateTextNode(node, lang);
  }
  root.querySelectorAll('[placeholder],[title],[aria-label],[alt],button[value],input[type=button][value],input[type=submit][value]').forEach(el => {
    if (el.closest(KKH_TRANSLATION_SKIP_SELECTOR)) return;
    let originals = kkhOriginalAttributes.get(el);
    if (!originals) { originals = new Map(); kkhOriginalAttributes.set(el, originals); }
    ['placeholder','title','aria-label','alt','value'].forEach(attr => {
      if (!el.hasAttribute(attr)) return;
      if (!originals.has(attr)) originals.set(attr, el.getAttribute(attr));
      const original = originals.get(attr);
      const translated = lookupKkhTranslation(original, lang);
      const next = translated !== null ? translated : original;
      if (el.getAttribute(attr) !== next) el.setAttribute(attr, next);
    });
  });
}
