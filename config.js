  let cleanFolder = String(folder).replace(/^books\//, '');
  if (!cleanFolder) cleanFolder = '';
  const encodedFolder = cleanFolder ? cleanFolder.split('/').map(encodeURIComponent).join('/') : '';
  const encodedFile = encodeURIComponent(file);
