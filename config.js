(function fillCrossLanguageTranslations() {
  const hasOwn = (obj, key) => Object.prototype.hasOwnProperty.call(obj, key);
  const rows = Object.entries(KKH_TRANSLATIONS.ru);
  rows.forEach(([source, russian]) => {
    const english = KKH_TRANSLATIONS.en[source];
    if (typeof russian !== 'string' || typeof english !== 'string') return;
    if (!hasOwn(KKH_TRANSLATIONS.en, russian)) KKH_TRANSLATIONS.en[russian] = english;
    if (!hasOwn(KKH_TRANSLATIONS.ru, english)) KKH_TRANSLATIONS.ru[english] = russian;
    if (!hasOwn(KKH_TRANSLATIONS.tg, russian)) KKH_TRANSLATIONS.tg[russian] = source;
    if (!hasOwn(KKH_TRANSLATIONS.tg, english)) KKH_TRANSLATIONS.tg[english] = source;
  });
})();

function lookupKkhTranslation(text, lang) {
  const dictionary = KKH_TRANSLATIONS[lang] || {};
  if (Object.prototype.hasOwnProperty.call(dictionary, text)) return dictionary[text];
  // Keep leading UI pictograms, bullets, arrows, or punctuation while translating the label.
  const leading = text.match(/^([^\p{L}\p{N}]*)([\p{L}\p{N}][\s\S]*)$/u);
  if (leading) {
    const core = leading[2].trim();
    if (Object.prototype.hasOwnProperty.call(dictionary, core)) return leading[1] + dictionary[core];
  }
  // Translate stable system-message prefixes and preserve the server-provided detail.
  const colonAt = text.indexOf(':');
  if (colonAt >= 0) {
    const prefix = text.slice(0, colonAt + 1);
    if (Object.prototype.hasOwnProperty.call(dictionary, prefix)) return dictionary[prefix] + text.slice(prefix.length);
  }
  return null;
}

